/**
 * Object storage for uploaded files (cat photos). Two drivers:
 *
 *   * S3-compatible (AWS S3, Cloudflare R2, MinIO, Backblaze B2…) when S3_BUCKET is set.
 *   * Local directory (LOCAL_STORAGE_DIR, default `.data/uploads` at the workspace root)
 *     otherwise, for development and tests.
 *
 * Objects are private: the API streams them to people allowed to see them.
 */
import { existsSync } from "node:fs";
import { mkdir, readFile, rm, writeFile } from "node:fs/promises";
import path from "node:path";

import {
  DeleteObjectCommand,
  GetObjectCommand,
  NoSuchKey,
  PutObjectCommand,
  S3Client,
} from "@aws-sdk/client-s3";
import { z } from "zod";

export interface PutObjectInput {
  key: string;
  body: string | Uint8Array;
  contentType: string;
  metadata?: Record<string, string>;
}

export interface StoredObject {
  body: Uint8Array;
  contentType: string;
}

export interface ObjectStorage {
  readonly driver: "s3" | "local";
  readonly bucket: string;
  put(input: PutObjectInput): Promise<void>;
  /** Object body and type, or null when the key does not exist. */
  get(key: string): Promise<StoredObject | null>;
  delete(key: string): Promise<void>;
}

export interface S3StorageConfig {
  bucket: string;
  region: string;
  /** Custom endpoint for non-AWS providers, e.g. https://<account>.r2.cloudflarestorage.com */
  endpoint?: string;
  accessKeyId?: string;
  secretAccessKey?: string;
  /** Path-style URLs (`endpoint/bucket/key`), required by MinIO and most self-hosted servers. */
  forcePathStyle?: boolean;
  /** Prepended to every key, e.g. `production/`. */
  prefix?: string;
}

/** Keys are generated by the application; this rejects anything path-like. */
function assertSafeKey(key: string): void {
  if (!/^[a-z0-9][a-z0-9/_.-]*$/i.test(key) || key.includes("..") || key.includes("//")) {
    throw new Error(`Invalid storage key: ${key}`);
  }
}

export function createS3Storage(config: S3StorageConfig): ObjectStorage {
  const client = new S3Client({
    region: config.region,
    endpoint: config.endpoint,
    forcePathStyle: config.forcePathStyle,
    credentials:
      config.accessKeyId && config.secretAccessKey
        ? { accessKeyId: config.accessKeyId, secretAccessKey: config.secretAccessKey }
        : undefined,
  });
  const prefix = config.prefix ?? "";
  return {
    driver: "s3",
    bucket: config.bucket,
    async put({ key, body, contentType, metadata }) {
      assertSafeKey(key);
      await client.send(
        new PutObjectCommand({
          Bucket: config.bucket,
          Key: prefix + key,
          Body: body,
          ContentType: contentType,
          Metadata: metadata,
        }),
      );
    },
    async get(key) {
      assertSafeKey(key);
      try {
        const result = await client.send(
          new GetObjectCommand({ Bucket: config.bucket, Key: prefix + key }),
        );
        if (!result.Body) return null;
        return {
          body: await result.Body.transformToByteArray(),
          contentType: result.ContentType ?? "application/octet-stream",
        };
      } catch (error) {
        if (error instanceof NoSuchKey) return null;
        throw error;
      }
    },
    async delete(key) {
      assertSafeKey(key);
      await client.send(new DeleteObjectCommand({ Bucket: config.bucket, Key: prefix + key }));
    },
  };
}

/** Files under `root`; the content type is kept in a sidecar `.type` file. */
export function createLocalStorage(root: string): ObjectStorage {
  const file = (key: string) => {
    assertSafeKey(key);
    return path.join(root, key);
  };
  return {
    driver: "local",
    bucket: root,
    async put({ key, body, contentType }) {
      const target = file(key);
      await mkdir(path.dirname(target), { recursive: true });
      await writeFile(target, body);
      await writeFile(`${target}.type`, contentType);
    },
    async get(key) {
      const target = file(key);
      try {
        const [body, contentType] = await Promise.all([
          readFile(target),
          readFile(`${target}.type`, "utf8").catch(() => "application/octet-stream"),
        ]);
        return { body: new Uint8Array(body), contentType };
      } catch (error) {
        if ((error as NodeJS.ErrnoException).code === "ENOENT") return null;
        throw error;
      }
    },
    async delete(key) {
      const target = file(key);
      await rm(target, { force: true });
      await rm(`${target}.type`, { force: true });
    },
  };
}

const optional = z
  .string()
  .optional()
  .transform((v) => (v?.trim() ? v.trim() : undefined));

const envSchema = z.object({
  S3_BUCKET: optional,
  S3_REGION: z.string().trim().min(1).default("auto"),
  S3_ENDPOINT: z
    .url()
    .optional()
    .or(z.literal("").transform(() => undefined)),
  S3_ACCESS_KEY_ID: optional,
  S3_SECRET_ACCESS_KEY: optional,
  S3_FORCE_PATH_STYLE: z
    .enum(["true", "false", ""])
    .optional()
    .transform((v) => v === "true"),
  S3_PREFIX: optional,
  LOCAL_STORAGE_DIR: optional,
});

function workspaceRoot(from = process.cwd()): string {
  let dir = path.resolve(from);
  while (!existsSync(path.join(dir, "pnpm-workspace.yaml"))) {
    const parent = path.dirname(dir);
    if (parent === dir) return process.cwd();
    dir = parent;
  }
  return dir;
}

/** S3 storage when S3_BUCKET is set, otherwise a local directory. */
export function storageFromEnv(env: NodeJS.ProcessEnv = process.env): ObjectStorage {
  const parsed = envSchema.safeParse(env);
  if (!parsed.success) {
    throw new Error(`Invalid storage configuration: ${z.prettifyError(parsed.error)}`);
  }
  const vars = parsed.data;
  if (!vars.S3_BUCKET) {
    return createLocalStorage(
      path.resolve(vars.LOCAL_STORAGE_DIR ?? path.join(workspaceRoot(), ".data", "uploads")),
    );
  }
  return createS3Storage({
    bucket: vars.S3_BUCKET,
    region: vars.S3_REGION,
    endpoint: vars.S3_ENDPOINT,
    accessKeyId: vars.S3_ACCESS_KEY_ID,
    secretAccessKey: vars.S3_SECRET_ACCESS_KEY,
    forcePathStyle: vars.S3_FORCE_PATH_STYLE,
    prefix: vars.S3_PREFIX,
  });
}

let instance: ObjectStorage | undefined;

export function getStorage(): ObjectStorage {
  instance ??= storageFromEnv();
  return instance;
}

/** Test hook. */
export function setStorage(storage: ObjectStorage | undefined): void {
  instance = storage;
}
